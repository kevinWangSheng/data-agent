"""`python -m evals livesqlbench-parity <step>`: ticket 136's oracle and the parity of our soft EX
with upstream's evaluator, on the server, once the gold answers are in the tasks.

    run     for every generated task with a gold answer: start its database image, then score
            (a) the gold SQL as the prediction, and (b) each dev trial's `pred.json` under
            --trials, once with our verifier (the task's own tests/test.sh in the `main` image, as
            Harbor runs it) and once with upstream's (LiveSQLBench @ UPSTREAM_COMMIT,
            LiveSQLBench-CLI/adapters/livesqlbench/template/tests/{test.sh,evaluator.py} with
            evaluation/src/ as its evaluator_src/, in an image of upstream's verifier environment:
            python:3.10-slim, postgresql-client, upstream's requirements.txt). The oracle is (a)
            on our side: every task must score 1. Parity: both sides' rewards must agree on every
            case. Writes OUT/reports/parity.json and prints the same summary.
    leaks   how often a gold SQL statement (whitespace-normalised, as written and as soft EX
            cleans it) occurs in the files under a directory; prints the count only

What leaves the server (ADR-0004, spec U7): the summary names dev tasks only (a holdout task is
in counts alone) and never holds a SQL statement, a result value or a driver message. Upstream's
evaluator logs every query and its result (evaluation/src/db_utils.py:302-304) and its test.sh
copies pred.json into debug.txt, so both evaluators write into a scratch directory outside
`runs/` (--scratch, by default ROOT/parity-scratch), read back as a reward and named flags, and
deleted case by case and at the end. Every container runs with `--rm` (Postgres logs a failed
statement) and is named by its database, not its task (`da-remote`'s memory.log records container
names). The write credential reaches the containers by variable name from
$LSB_PG_WRITE_PASSWORD, never on a command line.
"""

