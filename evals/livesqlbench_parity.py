@dataclass(frozen=True)
class Case:
    """One prediction to score on one task: the gold SQL (`source` "gold") or a trial's
    `pred.json` (`source` its job and trial name; dev tasks only)."""

    task: str
    task_dir: Path
    source: str
    prediction: bytes


@dataclass
class Side:
    """One evaluator's verdict on a case: its reward (None: it wrote none) and what it said
    without saying what (our diagnostics' outcome, error class and `pred.json` state; upstream's
    named flags)."""

    reward: float | None
    outcome: str | None = None
    error: str | None = None
    pred_json: str | None = None
    predicted_rows: int | None = None
    flags: list[str] = field(default_factory=lambda: [])


@dataclass
class Scored:
    case: Case
    ours: Side
    upstream: Side
    status: str
    rerun: bool = False


# --- what the two sides said ---


def compare(ours: Side, upstream: Side) -> str:
    """`agree` when both scored the case alike; `ours_no_reward` when our verifier wrote no
    reward (its own failure: rerun as infrastructure in a real run, so a case that always fails
    it is a verifier bug); `upstream_failed` when upstream's output says it did not score the
    prediction (a crash test.sh turned into 0.0, an exception evaluator.py swallowed into a 1);
    `disagree` otherwise."""
    if ours.reward is None:
        return "ours_no_reward"
    if upstream.reward is None or UPSTREAM_FAILURES & set(upstream.flags):
        return "upstream_failed"
    return "agree" if int(ours.reward) == int(upstream.reward) else "disagree"


def timed_out(scored: Scored) -> bool:
    return scored.ours.error == OUR_TIMEOUT or "timeout" in scored.upstream.flags


def oracle_category(ours: Side) -> str | None:
    """Why the gold SQL as the prediction did not score 1 on our side, in the ticket's classes:
    `execution_error` (a side's SQL failed or timed out), `empty_result`, `different_result`;
    `verifier_error` when it wrote no reward; else its outcome. None when it scored 1."""
    if ours.reward is None:
        return "verifier_error"
    if ours.reward == 1:
        return None
    if ours.outcome in ("predicted_error", "gold_error"):
        return "execution_error"
    if ours.outcome == "mismatch":
        return "empty_result" if ours.predicted_rows == 0 else "different_result"
    return ours.outcome or "unknown"


def read_ours(out: Path) -> Side:
    """Our verifier's reward.txt and diagnostics.json (evals.livesqlbench_verifier)."""
    try:
        reward: float | None = float((out / REWARD_FILE).read_text().strip())
    except (OSError, ValueError):
        reward = None
    try:
        loaded: Any = json.loads((out / DIAGNOSTICS_FILE).read_text())
    except (OSError, ValueError):
        loaded = {}
    found = cast(dict[str, Any], loaded if isinstance(loaded, dict) else {})
    rows = found.get("predicted_rows")
    return Side(
        reward=reward,
        outcome=found.get("outcome"),
        error=found.get("error"),
        pred_json=found.get("pred_json"),
        predicted_rows=rows if isinstance(rows, int) else None,
    )


def upstream_flags(text: str) -> list[str]:
    flags = {name for name, needles in UPSTREAM_MARKERS.items() if any(n in text for n in needles)}
    if "reward_written" in flags:
        flags.discard("evaluator_crashed")  # its exit 1 on a scored 0
    return sorted(flags)


def read_upstream(out: Path) -> Side:
    """Upstream's reward.txt (`1`, `0`, or test.sh's `0.0`) and the named flags of its logs."""
    try:
        reward: float | None = float((out / REWARD_FILE).read_text().strip())
    except (OSError, ValueError):
        reward = None
    text = ""
    for name in ("test.log", "evaluator_stdout.txt", "evaluator_stderr.txt"):
        path = out / name
        if path.is_file():
            text += path.read_text(errors="replace") + "\n"
    return Side(reward=reward, flags=upstream_flags(text))


# --- the server side: upstream's code and image ---


def upstream_checkout(root: Path, run: Run) -> Path:
    """Upstream LiveSQLBench at UPSTREAM_COMMIT under ROOT/upstream/, fetched once (that commit
    only) and checked by `git rev-parse` on every call."""
    dest = root / "upstream" / f"livesqlbench-{UPSTREAM_COMMIT[:7]}"

    def head(repo: Path) -> str:
        done = run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True)
        return done.stdout.strip() if done.returncode == 0 else ""

    if (dest / ".git").is_dir():
        if head(dest) != UPSTREAM_COMMIT:
            raise SystemExit(f"livesqlbench-parity: {dest} is not at {UPSTREAM_COMMIT}")
        return dest
    partial = dest.with_name(dest.name + ".partial")
    shutil.rmtree(partial, ignore_errors=True)
    partial.mkdir(parents=True)
    for cmd in (
        ["git", "-C", str(partial), "init", "-q"],
        ["git", "-C", str(partial), "fetch", "-q", "--depth", "1", UPSTREAM_REPO, UPSTREAM_COMMIT],
        ["git", "-C", str(partial), "checkout", "-q", "--detach", "FETCH_HEAD"],
    ):
        done = run(cmd, capture_output=True, text=True)
        if done.returncode != 0:
            tail = (done.stdout + done.stderr).strip().splitlines()[-3:]
            raise SystemExit(
                f"livesqlbench-parity: {' '.join(cmd[3:5])} failed: {' / '.join(tail)}"
            )
    if head(partial) != UPSTREAM_COMMIT:
        raise SystemExit(f"livesqlbench-parity: the fetched upstream is not {UPSTREAM_COMMIT}")
    partial.replace(dest)
    say(f"upstream: LiveSQLBench @ {UPSTREAM_COMMIT[:7]} fetched")
    return dest


def upstream_image() -> str:
    digest = hashlib.sha256(UPSTREAM_DOCKERFILE.encode()).hexdigest()[:8]
    return f"da-lsb-upstream-eval:{UPSTREAM_COMMIT[:7]}-{digest}"


def build_upstream_image(checkout: Path, work: Path, run: Run) -> str:
    image = upstream_image()
    if image_exists(run, image):
        say(f"image {image}: present")
        return image
    context = work / "upstream-image"
    shutil.rmtree(context, ignore_errors=True)
    context.mkdir(parents=True)
    shutil.copyfile(checkout / UPSTREAM_REQUIREMENTS, context / "requirements.txt")
    (context / "Dockerfile").write_text(UPSTREAM_DOCKERFILE)
    say(f"image {image}: building")
    try:
        done = run(
            ["docker", "build", "-q", "-t", image, str(context)], capture_output=True, text=True
        )
    finally:
        shutil.rmtree(context, ignore_errors=True)
    if done.returncode != 0:
        tail = (done.stdout + done.stderr).strip().splitlines()[-5:]
        raise SystemExit(
            f"livesqlbench-parity: docker build of {image} failed:\n" + "\n".join(tail)
        )
    return image


# --- the cases ---


def payload(task_dir: Path) -> dict[str, Any]:
    return json.loads((task_dir / "tests" / "task_payload.json").read_text(encoding="utf-8"))


def gold_prediction(task_dir: Path) -> bytes:
    """The task's gold SQL in `pred.json`'s format, as the agent would write it."""
    data = payload(task_dir)
    sol = data.get("sol_sql")
    sqls = sol if isinstance(sol, list) else [sol]  # pyright: ignore[reportUnknownVariableType]
    return json.dumps({"instance_id": data["instance_id"], "predicted_sql": sqls}).encode()


def scored_tasks(root: Path, only: Sequence[str]) -> list[Path]:
    """The generated tasks (all, or `only`), each refused unless it can be scored with this
    checkout's verifier: a gold answer, the repo's verifier script and test.sh, the current
    `main` image. Errors give counts only (no holdout task is named)."""
    tasks = sorted(p for p in (root / "tasks").glob(f"{TASK_PREFIX}*") if p.is_dir())
    if only:
        missing = len(set(only) - {t.name for t in tasks})
        if missing:
            raise SystemExit(f"livesqlbench-parity: {missing} --task id(s) have no generated task")
        tasks = [t for t in tasks if t.name in set(only)]
    if not tasks:
        raise SystemExit(f"livesqlbench-parity: no generated task under {root / 'tasks'}")
    verifier = VERIFIER_SCRIPT.read_bytes()
    problems = Counter[str]()
    for task in tasks:
        if not livesqlbench.has_gold_answer(task):
            problems["without a gold answer"] += 1
        tests = task / "tests"
        copy = tests / VERIFIER_SCRIPT.name
        if not copy.is_file() or copy.read_bytes() != verifier:
            problems["with another verifier than this checkout's"] += 1
        if not (tests / "test.sh").is_file() or (tests / "test.sh").read_text() != TEST_SH:
            problems["with another test.sh than this checkout's"] += 1
        if task_image(task) != livesqlbench.main_image():
            problems["naming another main image"] += 1
    if problems:
        what = "; ".join(f"{n} {why}" for why, n in sorted(problems.items()))
        raise SystemExit(
            f"livesqlbench-parity: of {len(tasks)} tasks, {what}; rerun da-remote benchmarks"
        )
    return tasks


def dev_set() -> set[str]:
    return set(json.loads((REPO_ROOT / "evals" / "manifest.json").read_text())["dev"])


@dataclass
class Found:
    cases: list[Case]
    holdout_skipped: int = 0
    without_prediction: int = 0


def trial_cases(trial_roots: Sequence[Path], tasks: Mapping[str, Path], dev: set[str]) -> Found:
    """The `pred.json` each trial under `trial_roots` keeps in its agent logs (evals.harbor_agent
    copies it there), for the dev tasks in `tasks`; a holdout task's trial is counted and never
    read (ADR-0004); a trial without one is counted (both sides score a missing file 0)."""
    found = Found(cases=[])
    for root in trial_roots:
        for result in sorted(root.rglob("result.json")):
            trial = result.parent
            try:
                name = json.loads(result.read_text()).get("task_name")
            except (OSError, ValueError, AttributeError):
                continue
            if not isinstance(name, str) or not task_id(name).startswith(TASK_PREFIX):
                continue  # the job's own result.json, or another benchmark's trial
            task = task_id(name)
            if task not in dev:
                found.holdout_skipped += 1
                continue
            if task not in tasks:
                continue
            prediction = trial / "agent" / "pred.json"
            if not prediction.is_file():
                found.without_prediction += 1
                continue
            source = f"{trial.parent.name}/{trial.name}"
            found.cases.append(Case(task, tasks[task], source, prediction.read_bytes()))
    return found


# --- running both evaluators ---


@dataclass(frozen=True)
class Harness:
    run: Run
    scratch: Path
    upstream: Path  # the checkout
    upstream_image: str
    password: str


def docker(h: Harness, args: list[str], timeout: float | None = None) -> int:
    """A docker command whose output stays unread (it may hold SQL): the exit code only, -1 on
    a timeout. The write credential is in its environment only."""
    env = os.environ | {"PGPASSWORD": h.password}
    try:
        return h.run(
            ["docker", *args], capture_output=True, text=True, env=env, timeout=timeout
        ).returncode
    except subprocess.TimeoutExpired:
        return -1


def verifier_env() -> list[str]:
    return [
        *("-e", f"PGHOST={DB_SERVICE}", "-e", "PGPORT=5432"),
        *("-e", f"PGUSER={WRITER_ROLE}", "-e", "PGPASSWORD"),
    ]


def upstream_tests(h: Harness, task_dir: Path, into: Path) -> None:
    """Upstream's tests/ as its adapter lays them out (adapter.py `_copy_template`,
    `_copy_eval_src`): test.sh, evaluator.py, evaluator_src/, and the task's payload."""
    shutil.copytree(h.upstream / UPSTREAM_TESTS, into)
    shutil.copytree(h.upstream / UPSTREAM_SRC, into / "evaluator_src")
    shutil.copyfile(task_dir / "tests" / "task_payload.json", into / "task_payload.json")


def score(h: Harness, network: str, case: Case) -> tuple[Side, Side]:
    """Both evaluators on one case, one after the other (both use `<db>_process_1`)."""
    work = Path(tempfile.mkdtemp(prefix="case-", dir=h.scratch))
    try:
        app = work / "app"
        app.mkdir()
        (app / "pred.json").write_bytes(case.prediction)
        ours, theirs, tests = work / "ours", work / "upstream", work / "tests"
        ours.mkdir()
        theirs.mkdir()
        upstream_tests(h, case.task_dir, tests)
        for name, image, tests_dir, out in (
            ("ours", livesqlbench.main_image(), case.task_dir / "tests", ours),
            ("upstream", h.upstream_image, tests, theirs),
        ):
            container = f"{network}-{name}"
            code = docker(
                h,
                [
                    *("run", "--rm", "--name", container, "--network", network),
                    *verifier_env(),
                    *("-v", f"{tests_dir.resolve()}:/tests:ro"),
                    *("-v", f"{app.resolve()}:/app:ro"),
                    *("-v", f"{out.resolve()}:/logs/verifier"),
                    *(image, "bash", "/tests/test.sh"),
                ],
                timeout=CASE_TIMEOUT_SEC,
            )
            if code == -1:
                docker(h, ["rm", "-f", container])
        return read_ours(ours), read_upstream(theirs)
    finally:
        shutil.rmtree(work, ignore_errors=True)


def run_group(h: Harness, database: str, cases: list[Case]) -> list[Scored]:
    """One database container for the cases of tasks sharing its database and `db_init` (both
    evaluators clone their process database from the image's template on every case)."""
    tag = hashlib.sha256(os.urandom(8)).hexdigest()[:8]
    network = f"da-lsb-parity-{database}-{tag}"
    db = f"{network}-db"
    init = (cases[0].task_dir / "environment" / "db_init").resolve()
    try:
        if docker(h, ["network", "create", network]) != 0:
            raise SystemExit(f"livesqlbench-parity: cannot create a network for {database}")
        started = docker(
            h,
            [
                *("run", "-d", "--rm", "--name", db, "--network", network),
                *("--network-alias", DB_SERVICE),
                *("-v", f"{init}:/docker-entrypoint-initdb.d/db_assets:ro"),
                livesqlbench.db_image(database),
            ],
        )
        if started != 0:
            raise SystemExit(f"livesqlbench-parity: the {database} database did not start")
        ready = ["exec", db, "pg_isready", "-U", "postgres", "-h", "127.0.0.1"]
        for _ in range(DB_READY_TRIES):
            if docker(h, ready) == 0:
                break
            h.run(["sleep", "2"], capture_output=True, text=True)
        else:
            raise SystemExit(f"livesqlbench-parity: the {database} database never got ready")
        results: list[Scored] = []
        for case in cases:
            ours, upstream = score(h, network, case)
            scored = Scored(case, ours, upstream, compare(ours, upstream))
            if scored.status != "agree" and timed_out(scored):
                ours, upstream = score(h, network, case)
                scored = Scored(case, ours, upstream, compare(ours, upstream), rerun=True)
            results.append(scored)
        return results
    finally:
        docker(h, ["rm", "-f", db])
        docker(h, ["network", "rm", network])


def groups(cases: Sequence[Case]) -> dict[tuple[str, str], list[Case]]:
    by: dict[tuple[str, str], list[Case]] = {}
    for case in cases:
        environment = case.task_dir / "environment"
        database = (environment / "db_init" / "db_name.txt").read_text().strip()
        preprocess = (environment / "db_init" / "preprocess.sql").read_bytes()
        by.setdefault((database, hashlib.sha256(preprocess).hexdigest()), []).append(case)
    return by


def score_all(h: Harness, cases: Sequence[Case], jobs: int) -> list[Scored]:
    with ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
        futures = [
            pool.submit(run_group, h, database, group)
            for (database, _), group in sorted(groups(cases).items())
        ]
        return [scored for future in futures for scored in future.result()]


# --- the summary ---


def side_fields(scored: Scored) -> dict[str, Any]:
    return {
        "status": scored.status,
        "ours_reward": scored.ours.reward,
        "ours_outcome": scored.ours.outcome,
        "ours_error": scored.ours.error,
        "pred_json": scored.ours.pred_json,
        "upstream_reward": scored.upstream.reward,
        "upstream_flags": scored.upstream.flags,
        "rerun": scored.rerun,
    }


def parity_summary(results: Sequence[Scored], dev: set[str], trials: bool) -> dict[str, Any]:
    """Counts over all cases; the disagreeing cases one by one for dev tasks only."""
    statuses = Counter(r.status for r in results)
    out: dict[str, Any] = {
        "cases": len(results),
        "agree": statuses["agree"],
        "by_status": dict(sorted(statuses.items())),
        "reruns": sum(r.rerun for r in results),
    }
    off = [r for r in results if r.status != "agree"]
    out["dev_disagree"] = [
        {"task": r.case.task, **({"trial": r.case.source} if trials else {}), **side_fields(r)}
        for r in off
        if r.case.task in dev
    ]
    out["holdout_disagree"] = sum(r.case.task not in dev for r in off)
    return out


def oracle_summary(results: Sequence[Scored], dev: set[str]) -> dict[str, Any]:
    wrong = [(r, oracle_category(r.ours)) for r in results]
    wrong = [(r, c) for r, c in wrong if c is not None]
    return {
        "right": len(results) - len(wrong),
        "of": len(results),
        "wrong_by_category": dict(sorted(Counter(c for _, c in wrong).items())),
        "dev_wrong": [
            {"task": r.case.task, "category": c, "error": r.ours.error}
            for r, c in wrong
            if r.case.task in dev
        ],
        "holdout_wrong_by_category": dict(
            sorted(Counter(c for r, c in wrong if r.case.task not in dev).items())
        ),
    }


def summary_lines(summary: Mapping[str, Any]) -> list[str]:
    oracle, gold, preds = summary["oracle"], summary["parity_gold"], summary["parity_trials"]
    lines = [
        f"upstream: {summary['upstream']}",
        f"tasks: {summary['tasks']} ({summary['dev_tasks']} dev, {summary['holdout_tasks']} "
        "holdout)",
        f"oracle: {oracle['right']}/{oracle['of']} scored 1 with the gold SQL"
        + (f"; not: {oracle['wrong_by_category']}" if oracle["wrong_by_category"] else ""),
    ]
    lines += [
        f"  oracle dev {w['task']}: {w['category']} ({w['error']})" for w in oracle["dev_wrong"]
    ]
    if oracle["holdout_wrong_by_category"]:
        lines.append(f"  oracle holdout: {oracle['holdout_wrong_by_category']}")
    for label, part in (("gold SQL", gold), ("dev trials' pred.json", preds)):
        lines.append(
            f"parity on {label}: {part['agree']}/{part['cases']} agree {part['by_status']}"
            + (f", {part['reruns']} rerun after a timeout" if part["reruns"] else "")
        )
        for d in part["dev_disagree"]:
            where = d["task"] + (f" {d['trial']}" if "trial" in d else "")
            lines.append(
                f"  dev {where}: {d['status']}: ours {d['ours_reward']} ({d['ours_outcome']}, "
                f"{d['ours_error']}, pred.json {d['pred_json']}), upstream "
                f"{d['upstream_reward']} {d['upstream_flags']}"
            )
        if part["holdout_disagree"]:
            lines.append(f"  holdout: {part['holdout_disagree']} not agreeing")
    lines.append(
        f"trials: {preds['cases']} dev trial(s) with pred.json, "
        f"{summary['trials_without_pred_json']} without, "
        f"{summary['holdout_trials_skipped']} holdout trial(s) not read"
    )
    lines.append(f"scratch: {'removed' if summary['scratch_removed'] else 'NOT removed'}")
    return lines


def check_scratch(scratch: Path, out: Path) -> None:
    """The scratch directory holds upstream's logs (every gold query): never under `runs/` or
    OUT, which `da-remote pull` brings back."""
    resolved = scratch.resolve()
    for forbidden in (REPO_ROOT / "runs", out):
        if resolved.is_relative_to(forbidden.resolve()):
            raise SystemExit(f"livesqlbench-parity: --scratch must not be under {forbidden}")
    # It is deleted before and after a run: only one this command made (a killed run's) may be.
    if scratch.exists() and not (scratch / SCRATCH_MARKER).is_file():
        raise SystemExit(f"livesqlbench-parity: {scratch} exists and is no scratch of this command")


def fresh_scratch(scratch: Path) -> None:
    shutil.rmtree(scratch, ignore_errors=True)
    scratch.mkdir(parents=True, mode=0o700)
    (scratch / SCRATCH_MARKER).write_text("livesqlbench-parity scratch; deleted after each run\n")


def parity(
    root: Path,
    out: Path,
    trial_roots: Sequence[Path],
    scratch: Path,
    only: Sequence[str] = (),
    jobs: int = 3,
    run: Run = subprocess.run,
) -> dict[str, Any]:
    """The oracle and both parity checks (module docstring); writes OUT/reports/parity.json."""
    check_scratch(scratch, out)
    password = write_password()
    dev = dev_set()
    # ADR-0004: a holdout task scored alone would give its own outcome; the holdout runs whole.
    if held := sum(task not in dev for task in set(only)):
        raise SystemExit(f"livesqlbench-parity: {held} --task id(s) are holdout tasks; give none")
    tasks = scored_tasks(root, only)
    by_id = {t.name: t for t in tasks}
    for trial_root in trial_roots:
        if not trial_cases([trial_root], by_id, dev).cases:
            raise SystemExit(
                f"livesqlbench-parity: --trials {trial_root} has no dev trial with a pred.json"
            )
    found = trial_cases(trial_roots, by_id, dev)
    fresh_scratch(scratch)
    try:
        checkout = upstream_checkout(root, run)
        h = Harness(run, scratch, checkout, build_upstream_image(checkout, scratch, run), password)
        gold = [Case(t.name, t, "gold", gold_prediction(t)) for t in tasks]
        say(f"scoring: {len(gold)} gold case(s), {len(found.cases)} dev trial case(s)")
        results = score_all(h, [*gold, *found.cases], jobs)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    on_gold = [r for r in results if r.case.source == "gold"]
    on_trials = [r for r in results if r.case.source != "gold"]
    summary: dict[str, Any] = {
        "upstream": f"{UPSTREAM_REPO}@{UPSTREAM_COMMIT}",
        "tasks": len(tasks),
        "dev_tasks": sum(t.name in dev for t in tasks),
        "holdout_tasks": sum(t.name not in dev for t in tasks),
        "oracle": oracle_summary(on_gold, dev),
        "parity_gold": parity_summary(on_gold, dev, trials=False),
        "parity_trials": parity_summary(on_trials, dev, trials=True),
        "trials_without_pred_json": found.without_prediction,
        "holdout_trials_skipped": found.holdout_skipped,
        "scratch_removed": not scratch.exists(),
    }
    reports = out / "reports"
    reports.mkdir(parents=True, exist_ok=True)
    (reports / "parity.json").write_text(json.dumps(summary, indent=2) + "\n")
    for line in summary_lines(summary):
        say(line)
    return summary


def passed(summary: Mapping[str, Any]) -> bool:
    oracle = summary["oracle"]
    return (
        oracle["right"] == oracle["of"]
        and summary["parity_gold"]["agree"] == summary["parity_gold"]["cases"]
        and summary["parity_trials"]["agree"] == summary["parity_trials"]["cases"]
        and summary["scratch_removed"]
    )


# --- the gold SQL sentinel ---


def sentinels(answers: Path) -> set[str]:
    """Each gold statement of the answer file, whitespace-normalised, as written and as soft EX
    cleans it, each also as a JSON string holds it (a pred.json, upstream's debug.txt: newlines and
    quotes escaped, with or without ASCII escapes); statements shorter than SENTINEL_MIN_CHARS are
    left out (no gold statement is that short, and a fragment would match unrelated text)."""
    found: set[str] = set()
    for record in livesqlbench.read_jsonl(answers):
        for sql in statements(record.get("sol_sql")):
            for variant in (sql, *clean_sql([sql])):
                for form in (
                    variant,
                    json.dumps(variant)[1:-1],
                    json.dumps(variant, ensure_ascii=False)[1:-1],
                ):
                    normalised = " ".join(form.split())
                    if len(normalised) >= SENTINEL_MIN_CHARS:
                        found.add(normalised)
    return found


def count_gold(answers: Path, root: Path) -> int:
    """How often a gold statement (`sentinels`) occurs in the files under `root`."""
    needles = sentinels(answers)
    total = 0
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        text = " ".join(path.read_bytes().decode("utf-8", errors="replace").split())
        total += sum(text.count(needle) for needle in needles)
    return total


# --- the command line ---


def run_step(args: argparse.Namespace) -> int:
    if args.step == "run":
        scratch = args.scratch or args.root / "parity-scratch"
        summary = parity(args.root, args.out, args.trials, scratch, args.task, args.jobs)
        return 0 if passed(summary) else 1
    found = count_gold(args.answers, args.dir)
    say(f"gold SQL: {found} occurrence(s) under {args.dir}")
    return 1 if found else 0


def add_parser(commands: "argparse._SubParsersAction[argparse.ArgumentParser]") -> None:
    parser = commands.add_parser(
        "livesqlbench-parity", help="LiveSQLBench oracle and parity with upstream's evaluator"
    )
    steps = parser.add_subparsers(dest="step", required=True)
    p = steps.add_parser("run", help="on the server: the oracle and both parity checks")
    p.add_argument("--root", type=Path, required=True, help="da-benchmarks/livesqlbench")
    p.add_argument("--out", type=Path, required=True, help="runs/<name>: reports/parity.json")
    p.add_argument(
        "--trials",
        type=Path,
        action="append",
        default=[],
        help="a run directory whose dev trials' pred.json are scored (repeatable)",
    )
    p.add_argument("--scratch", type=Path, help="default ROOT/parity-scratch; never under runs/")
    p.add_argument("--task", action="append", default=[], help="only these task ids")
    p.add_argument("--jobs", type=int, default=3, help="databases scored at a time")
    p = steps.add_parser("leaks", help="how often a gold SQL statement occurs under a directory")
    p.add_argument("--answers", type=Path, required=True)
    p.add_argument("--dir", type=Path, required=True)
    parser.set_defaults(run=run_step)
