"""Locked wheels for a container's platform (evals.wheels): picked from uv.lock, checked against
requirements.txt's hashes, fetched once into a cache on this machine. Downloads are faked."""

import hashlib
import json
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from evals import wheels  # noqa: E402
from evals.wheels import Platform  # noqa: E402

FILES = "https://files.example/"

# The probe's output in data-eng-bench's image (python:3.12-slim, Debian bookworm) on a Mac.
AARCH64 = {
    "markers": {
        "implementation_name": "cpython",
        "implementation_version": "3.12.13",
        "os_name": "posix",
        "platform_machine": "aarch64",
        "platform_python_implementation": "CPython",
        "platform_release": "6.8.0",
        "platform_system": "Linux",
        "platform_version": "#1 SMP",
        "python_full_version": "3.12.13",
        "python_version": "3.12",
        "sys_platform": "linux",
    },
    "libc": ["glibc", "2.36"],
}


def x86_64() -> dict[str, object]:
    markers = dict(AARCH64["markers"], platform_machine="x86_64")  # type: ignore[arg-type]
    return {"markers": markers, "libc": ["glibc", "2.36"]}


def content(name: str) -> bytes:
    return f"wheel {name}".encode()


def sha(name: str) -> str:
    return hashlib.sha256(content(name)).hexdigest()


def lock_package(name: str, version: str, *files: str) -> str:
    rows = "".join(
        f'    {{ url = "{FILES}{f}", hash = "sha256:{sha(f)}", size = 1 }},\n' for f in files
    )
    return f'[[package]]\nname = "{name}"\nversion = "{version}"\nwheels = [\n{rows}]\n\n'


ORJSON = (
    "orjson-3.11.0-cp312-cp312-macosx_11_0_arm64.whl",
    "orjson-3.11.0-cp312-cp312-manylinux_2_17_aarch64.manylinux2014_aarch64.whl",
    "orjson-3.11.0-cp312-cp312-manylinux_2_17_x86_64.manylinux2014_x86_64.whl",
    "orjson-3.11.0-cp313-cp313-manylinux_2_17_aarch64.manylinux2014_aarch64.whl",
    "orjson-3.11.0-cp312-cp312-musllinux_1_2_aarch64.whl",
)
CRYPTOGRAPHY = (
    "cryptography-46.0.0-cp311-abi3-manylinux_2_28_aarch64.whl",
    "cryptography-46.0.0-cp311-abi3-manylinux_2_34_aarch64.whl",
    "cryptography-46.0.0-cp311-abi3-manylinux_2_39_aarch64.whl",
    "cryptography-46.0.0-cp311-abi3-manylinux_2_28_x86_64.whl",
)
ANYIO = ("anyio-4.9.0-py3-none-any.whl",)
PYWIN32 = ("pywin32-312-cp312-cp312-win_amd64.whl",)

LOCK = (
    "version = 1\n\n"
    + lock_package("orjson", "3.11.0", *ORJSON)
    + lock_package("cryptography", "46.0.0", *CRYPTOGRAPHY)
    + lock_package("anyio", "4.9.0", *ANYIO)
    + lock_package("pywin32", "312", *PYWIN32)
)


def requirement(spec: str, *files: str) -> str:
    hashes = "".join(f" \\\n    --hash=sha256:{sha(f)}" for f in files)
    return f"{spec}{hashes}\n    # via data-agent\n"


REQUIREMENTS = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv export --frozen --no-dev --no-emit-project --format requirements.txt\n"
    + requirement("anyio==4.9.0", *ANYIO)
    + requirement("cryptography==46.0.0", *CRYPTOGRAPHY)
    + requirement("orjson==3.11.0", *ORJSON)
    + requirement("pywin32==312 ; sys_platform == 'win32'", *PYWIN32)
)


@pytest.fixture
def served(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> list[str]:
    """Every lock file served by URL without the network; returns the URLs fetched."""
    urls: list[str] = []

    def download(url: str, dest: Path) -> None:
        urls.append(url)
        dest.write_bytes(content(url.removeprefix(FILES)))

    monkeypatch.setattr(wheels, "download", download)
    monkeypatch.setattr(wheels, "CACHE_DIR", tmp_path / "cache")
    monkeypatch.setattr(wheels, "_wheelhouses", {})
    return urls


@pytest.fixture
def locked(tmp_path: Path) -> tuple[Path, Path]:
    lock = tmp_path / "uv.lock"
    lock.write_text(LOCK)
    requirements = tmp_path / "requirements.txt"
    requirements.write_text(REQUIREMENTS)
    return requirements, lock


def names(paths: list[Path] | list[wheels.Wheel]) -> set[str]:
    return {path.name for path in paths}


def test_the_probe_reads_the_containers_platform() -> None:
    platform = Platform.from_probe(json.dumps(AARCH64))
    assert platform.machine == "aarch64"
    assert platform.python == (3, 12)
    assert platform.glibc == (2, 36)


def test_a_musl_or_non_cpython_container_is_refused() -> None:
    with pytest.raises(RuntimeError, match="glibc"):
        Platform.from_probe(json.dumps(AARCH64 | {"libc": ["", ""]}))
    pypy = dict(AARCH64["markers"], implementation_name="pypy")  # type: ignore[arg-type]
    with pytest.raises(RuntimeError, match="CPython"):
        Platform.from_probe(json.dumps(AARCH64 | {"markers": pypy}))


def test_the_container_gets_the_wheel_built_for_its_arch_python_and_glibc(
    served: list[str], locked: tuple[Path, Path]
) -> None:
    platform = Platform.from_probe(json.dumps(AARCH64))
    picked = names(wheels.select(*locked, platform))
    assert picked == {
        "anyio-4.9.0-py3-none-any.whl",
        # cp312 on aarch64 with glibc: not macOS, x86_64, cp313 or musl.
        "orjson-3.11.0-cp312-cp312-manylinux_2_17_aarch64.manylinux2014_aarch64.whl",
        # The newest glibc the container has (2.36), not one it lacks (2.39).
        "cryptography-46.0.0-cp311-abi3-manylinux_2_34_aarch64.whl",
    }  # pywin32's marker is false on Linux.


def test_platforms_are_picked_apart(served: list[str], locked: tuple[Path, Path]) -> None:
    platform = Platform.from_probe(json.dumps(x86_64()))
    picked = names(wheels.select(locked[0], locked[1], platform))
    assert "orjson-3.11.0-cp312-cp312-manylinux_2_17_x86_64.manylinux2014_x86_64.whl" in picked
    assert "cryptography-46.0.0-cp311-abi3-manylinux_2_28_x86_64.whl" in picked


def test_a_requirement_without_a_wheel_for_the_platform_is_an_error(
    served: list[str], locked: tuple[Path, Path]
) -> None:
    old_glibc = AARCH64 | {"libc": ["glibc", "2.17"]}  # cryptography needs 2.28
    platform = Platform.from_probe(json.dumps(old_glibc))
    with pytest.raises(RuntimeError, match=r"cryptography==46\.0\.0.*glibc 2\.17"):
        wheels.wheelhouse(*locked, platform)


def test_a_lock_wheel_whose_hash_requirements_does_not_list_is_not_used(
    served: list[str], locked: tuple[Path, Path]
) -> None:
    requirements, _ = locked
    ours = "orjson-3.11.0-cp312-cp312-manylinux_2_17_aarch64.manylinux2014_aarch64.whl"
    requirements.write_text(REQUIREMENTS.replace(sha(ours), "0" * 64))
    with pytest.raises(RuntimeError, match=r"orjson==3\.11\.0"):
        wheels.wheelhouse(*locked, Platform.from_probe(json.dumps(AARCH64)))


def test_wheels_are_fetched_into_the_cache_and_staged_for_upload(
    served: list[str], locked: tuple[Path, Path]
) -> None:
    house = wheels.wheelhouse(*locked, Platform.from_probe(json.dumps(AARCH64)))
    staged = sorted(house.glob("*.whl"))
    assert len(staged) == 3 and len(served) == 3
    for path in staged:
        assert path.read_bytes() == content(path.name)
        assert (wheels.CACHE_DIR / path.name).read_bytes() == content(path.name)
    assert not list(wheels.CACHE_DIR.glob("*.part"))


def test_a_cached_wheel_is_not_downloaded_again(
    served: list[str], locked: tuple[Path, Path], monkeypatch: pytest.MonkeyPatch
) -> None:
    platform = Platform.from_probe(json.dumps(AARCH64))
    wheels.wheelhouse(*locked, platform)
    monkeypatch.setattr(wheels, "_wheelhouses", {})  # a new process: only the disk cache is left
    served.clear()
    wheels.wheelhouse(*locked, platform)
    assert served == []


def test_a_download_with_the_wrong_hash_is_refused_and_not_cached(
    served: list[str], locked: tuple[Path, Path], monkeypatch: pytest.MonkeyPatch
) -> None:
    def tampered(url: str, dest: Path) -> None:
        dest.write_bytes(b"not the locked wheel")

    monkeypatch.setattr(wheels, "download", tampered)
    with pytest.raises(RuntimeError, match="sha256"):
        wheels.wheelhouse(*locked, Platform.from_probe(json.dumps(AARCH64)))
    assert not list(wheels.CACHE_DIR.iterdir())


def test_a_corrupt_cache_entry_is_fetched_again(served: list[str], tmp_path: Path) -> None:
    name = ANYIO[0]
    wheels.CACHE_DIR.mkdir(parents=True)
    (wheels.CACHE_DIR / name).write_bytes(b"cut short")
    path = wheels.fetch(FILES + name, sha(name))
    assert path.read_bytes() == content(name)
    assert served == [FILES + name]


def task_dir(root: Path, toml: str = "", dockerfile: str | None = None) -> Path:
    task = root / "task"
    (task / "environment").mkdir(parents=True)
    (task / "task.toml").write_text(toml)
    if dockerfile is not None:
        (task / "environment" / "Dockerfile").write_text(dockerfile)
    return task


def test_a_tasks_image_is_the_base_of_its_dockerfiles_last_stage(tmp_path: Path) -> None:
    dockerfile = (
        "# a comment\nFROM --platform=$BUILDPLATFORM python:3.12 AS build\n"
        "from ghcr.io/snowflake-labs/data-eng-bench-base:1.0.0\nCOPY . /app\n"
    )
    task = task_dir(tmp_path, "[environment]\ncpus = 2\n", dockerfile)
    assert wheels.task_image(task) == "ghcr.io/snowflake-labs/data-eng-bench-base:1.0.0"


def test_a_last_stage_from_an_earlier_stage_resolves_to_that_stages_image(tmp_path: Path) -> None:
    dockerfile = (
        "FROM ghcr.io/snowflake-labs/data-eng-bench-base:1.0.0 AS Base\n"
        "FROM base as builder\nRUN make\n"
        "FROM python:3.12 AS other\n"
        "FROM BUILDER\nCOPY --from=other /x /x\n"
    )
    task = task_dir(tmp_path, "", dockerfile)
    assert wheels.task_image(task) == "ghcr.io/snowflake-labs/data-eng-bench-base:1.0.0"


def test_a_tasks_prebuilt_image_comes_first(tmp_path: Path) -> None:
    task = task_dir(tmp_path, '[environment]\ndocker_image = "org/prebuilt:2"\n', "FROM other\n")
    assert wheels.task_image(task) == "org/prebuilt:2"


@pytest.mark.parametrize("dockerfile", [None, "COPY . /app\n", "ARG BASE\nFROM $BASE\n"])
def test_a_task_without_a_known_image_is_an_error(tmp_path: Path, dockerfile: str | None) -> None:
    task = task_dir(tmp_path, "", dockerfile)
    with pytest.raises((RuntimeError, OSError)):
        wheels.task_image(task)


def probed(monkeypatch: pytest.MonkeyPatch, platforms: dict[str, dict[str, object]]) -> list[str]:
    """`probe` answering from `platforms` by image, without Docker; returns the images probed."""
    images: list[str] = []

    def probe(image: str) -> Platform:
        images.append(image)
        return Platform.from_probe(json.dumps(platforms[image]))

    monkeypatch.setattr(wheels, "probe", probe)
    return images


def test_fill_caches_each_platform_once(
    served: list[str], locked: tuple[Path, Path], monkeypatch: pytest.MonkeyPatch
) -> None:
    images = probed(monkeypatch, {"a": AARCH64, "b": AARCH64, "x": x86_64()})
    lines = wheels.fill(["b", "a", "x", "a"], *locked)
    assert images == ["a", "b", "x"]
    assert len(lines) == 2
    assert "aarch64" in lines[0] and "3 wheels" in lines[0]
    assert "x86_64" in lines[1]
    # anyio is shared; orjson and cryptography are fetched for each architecture.
    assert len(served) == 5
    cached = {p.name for p in wheels.CACHE_DIR.iterdir()}
    assert "orjson-3.11.0-cp312-cp312-manylinux_2_17_x86_64.manylinux2014_x86_64.whl" in cached


def test_fill_with_a_full_cache_goes_to_no_network(
    served: list[str], locked: tuple[Path, Path], monkeypatch: pytest.MonkeyPatch
) -> None:
    probed(monkeypatch, {"a": AARCH64})
    wheels.fill(["a"], *locked)
    monkeypatch.setattr(wheels, "_wheelhouses", {})  # the next ablate: only the disk cache is left

    def offline(url: str, dest: Path) -> None:
        raise AssertionError(f"downloaded {url}")

    monkeypatch.setattr(wheels, "download", offline)
    (line,) = wheels.fill(["a"], *locked)
    assert "3 wheels" in line


def test_a_failed_probe_says_why(monkeypatch: pytest.MonkeyPatch) -> None:
    def docker(args: list[str], **kwargs: object) -> SimpleNamespace:
        assert args[:2] == ["docker", "run"]
        return SimpleNamespace(returncode=125, stdout="", stderr="pull access denied\n")

    monkeypatch.setattr(wheels.subprocess, "run", docker)
    with pytest.raises(RuntimeError, match="cannot probe img:1: pull access denied"):
        wheels.probe("img:1")
